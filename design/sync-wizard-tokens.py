#!/usr/bin/env python3
"""Copy the Pebble Drift tokens (part 1 of
docs/mockups/concepts-2026/pebble-drift/pebble-drift.css, the design's source
of truth) into the migration wizard, which reads them at run time
(migration-wizard/lucent_migrate/tokens.css). Run after every token change;
the wizard's tests fail while the copy is stale."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "migration-wizard"))
from lucent_migrate import tokens  # noqa: E402

SOURCE = ROOT / "docs/mockups/concepts-2026/pebble-drift/pebble-drift.css"
HEADER = """/* Pebble Drift tokens for the "Move from Windows" wizard (lucent_migrate/tokens.py).
   Generated by design/sync-wizard-tokens.py from part 1 of
   docs/mockups/concepts-2026/pebble-drift/pebble-drift.css; do not edit by hand. */

"""

tokens.TOKENS_CSS.write_text(HEADER + tokens.extract(SOURCE.read_text(encoding="utf-8")), encoding="utf-8")
print(tokens.TOKENS_CSS)
