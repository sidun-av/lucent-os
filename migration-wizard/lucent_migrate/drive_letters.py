"""Give Windows partitions familiar names ("Local Disk (C:)", "Data (D:)").

At boot, `lucent-drive-letters.service` runs `main()` as root: it lists NTFS
volumes, probes which one holds Windows (without mounting, via ntfsprogs'
`ntfsls`), assigns letters the way Windows usually does, and writes a
runtime udev rule setting UDISKS_NAME (in the system language). udisks exposes that as the volume's
HintName, which Dolphin and the Plasma device notifier display.
"""

from __future__ import annotations

import string
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

from .i18n import _
from .volumes import Volume, run_lsblk

MIN_SIZE = 1024**3  # smaller NTFS partitions are OEM/recovery tools
RULES_PATH = Path("/run/udev/rules.d/61-lucent-drive-letters.rules")


def assign(vols: list[Volume], is_system: Callable[[Volume], bool]) -> dict[str, str]:
    """Map volume UUID -> drive letter. The Windows system volume gets C:,
    then internal disks in device order, then removable ones."""
    candidates = [
        v for v in vols
        if v.uuid and not v.recovery and not v.bitlocker and v.size >= MIN_SIZE
    ]
    candidates.sort(key=lambda v: (v.removable, v.path))
    system = next((v for v in candidates if is_system(v)), None)
    if system is None:
        system = next((v for v in candidates if not v.removable), None)
    ordered = ([system] if system else []) + [v for v in candidates if v is not system]
    letters = iter(string.ascii_uppercase[2:])  # A: and B: are floppies, still
    return {v.uuid: next(letters) for v in ordered}


def display_name(letter: str, label: str | None) -> str:
    """As Windows Explorer shows it: "Local Disk (C:)", or "Data (D:)" with a label."""
    if label:
        return _("{label} ({letter}:)").format(label=label, letter=letter)
    return _("Local Disk ({letter}:)").format(letter=letter)


def udev_rules(letters: dict[str, str], vols: list[Volume]) -> str:
    labels = {v.uuid: v.label for v in vols}
    lines = ["# Generated by lucent-drive-letters at boot; do not edit."]
    for uuid, letter in letters.items():
        name = display_name(letter, labels.get(uuid)).replace('"', "").replace("\\", "")
        lines.append(
            f'SUBSYSTEM=="block", ENV{{ID_FS_UUID}}=="{uuid}", ENV{{UDISKS_NAME}}="{name}"'
        )
    return "\n".join(lines) + "\n"


def probe_cmd(device: str) -> list[str]:
    # -f: also works when Windows is hibernated / Fast Startup left it dirty
    return ["ntfsls", "-f", "-p", "/Windows/System32", device]


def _probe(vol: Volume) -> bool:
    try:
        return subprocess.run(probe_cmd(vol.path), capture_output=True, timeout=20).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def main() -> int:
    vols = run_lsblk()
    letters = assign(vols, _probe)
    RULES_PATH.parent.mkdir(parents=True, exist_ok=True)
    RULES_PATH.write_text(udev_rules(letters, vols))
    subprocess.run(["udevadm", "control", "--reload"], check=False)
    subprocess.run(
        ["udevadm", "trigger", "--action=change", "--subsystem-match=block", "--property-match=ID_FS_TYPE=ntfs"],
        check=False,
    )
    for uuid, letter in letters.items():
        print(f"{letter}: {uuid}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
