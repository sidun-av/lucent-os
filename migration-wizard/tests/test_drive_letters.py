from lucent_migrate import drive_letters
from lucent_migrate.volumes import Volume

GIB = 1024**3


def vol(path, size=100 * GIB, label=None, uuid=None, disk=None, removable=False, **kw):
    return Volume(path=path, fstype="ntfs", size=size, label=label,
                  uuid=uuid or path.rsplit("/", 1)[-1].upper(), disk=disk or path[:-1],
                  removable=removable, **kw)


def test_system_volume_gets_c_even_if_not_first():
    data = vol("/dev/sda1", label="Data", disk="/dev/sda")
    system = vol("/dev/sdb2", label="OS", disk="/dev/sdb")
    letters = drive_letters.assign([data, system], is_system=lambda v: v is system)
    assert letters == {system.uuid: "C", data.uuid: "D"}


def test_internal_before_removable_and_skips_recovery_small_bitlocker():
    usb = vol("/dev/sdc1", removable=True, disk="/dev/sdc")
    rec = vol("/dev/nvme0n1p4", size=700 * 1024**2, recovery=True, disk="/dev/nvme0n1")
    tiny = vol("/dev/nvme0n1p2", size=500 * 1024**2, disk="/dev/nvme0n1")
    bl = Volume(path="/dev/nvme0n1p9", fstype="BitLocker", size=50 * GIB, uuid="BL", disk="/dev/nvme0n1")
    c = vol("/dev/nvme0n1p3", disk="/dev/nvme0n1")
    d = vol("/dev/nvme0n1p5", disk="/dev/nvme0n1")
    letters = drive_letters.assign([usb, rec, tiny, bl, d, c], is_system=lambda v: False)
    # no Windows folder detected: largest/first internal partition becomes C:
    assert letters == {c.uuid: "C", d.uuid: "D", usb.uuid: "E"}


def test_volumes_without_uuid_are_skipped():
    v = Volume(path="/dev/sdz1", fstype="ntfs", size=10 * GIB, uuid=None)
    assert drive_letters.assign([v], is_system=lambda v: False) == {}


def test_display_name():
    assert drive_letters.display_name("C", None) == "Диск C:"
    assert drive_letters.display_name("D", "Data") == "Диск D: (Data)"


def test_udev_rules_text_escapes_quotes():
    c = vol("/dev/sda1", uuid="01D9AAAA", label='My "disk"')
    text = drive_letters.udev_rules({"01D9AAAA": "C"}, [c])
    assert 'ENV{ID_FS_UUID}=="01D9AAAA"' in text
    assert 'ENV{UDISKS_NAME}="Диск C: (My disk)"' in text
    assert text.startswith("# Generated by lucent-drive-letters")


def test_ntfsls_probe_command():
    assert drive_letters.probe_cmd("/dev/sda1") == ["ntfsls", "-f", "-p", "/Windows/System32", "/dev/sda1"]
